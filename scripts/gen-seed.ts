// Writes supabase/seed.sql from the bundled pathway content so the database and
// the app start from the same reviewed text. Run: npm run gen:seed
import { writeFileSync } from "node:fs";
import { PATHWAYS } from "../src/data/pathways";

const quote = (value: string) => `'${value.replace(/'/g, "''")}'`;

const rows = PATHWAYS.map((p) => `  (${quote(p.id)}, ${quote(JSON.stringify(p))}::jsonb, '2026-11-04', 'KiwiPath content team (needs licensed adviser review)')`);

const sql = `-- Generated by scripts/gen-seed.ts. Do not edit by hand: change src/data/pathways.ts and re-run \`npm run gen:seed\`.
insert into public.pathways (id, content, checked_on, reviewed_by) values
${rows.join(",\n")}
on conflict (id) do update set content = excluded.content, checked_on = excluded.checked_on, reviewed_by = excluded.reviewed_by;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql written with ${PATHWAYS.length} pathways`);
